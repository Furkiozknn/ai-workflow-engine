"""Render a validated pipeline's DAG as Mermaid or Graphviz DOT text.

``awe graph`` prints it. Mermaid renders inline on GitHub, GitLab and most
Markdown viewers, so a pipeline's shape can sit in its README or a pull
request; DOT goes through Graphviz (``awe graph p.yaml --format dot | dot
-Tsvg > p.svg``), the way ``snakemake --dag`` does.

Both renderings come from the same two facts the runner uses: each step's
``depends_on`` (the edges) and ``pipeline.execution_layers`` (which steps
run side by side). Nothing is inferred from template strings, so the
picture shows exactly the order a run will use.
"""

from __future__ import annotations

from .pipeline import Pipeline, execution_layers
from .templating import find_var_references

FORMATS = ("mermaid", "dot")


def _mermaid_text(value: str) -> str:
    """Escape text for a quoted Mermaid label.

    Mermaid decodes ``#name;`` / ``#123;`` entity codes inside labels, so
    ``#`` itself must be encoded first; quotes would end the label and
    ``<``/``>``/``&`` would be read as HTML when htmlLabels is on.
    """
    return (
        value.replace("#", "#35;")
        .replace('"', "#quot;")
        .replace("<", "#lt;")
        .replace(">", "#gt;")
        .replace("&", "#amp;")
    )


def _dot_text(value: str) -> str:
    """Escape text for a double-quoted DOT string."""
    return value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def _step_vars(pipeline: Pipeline) -> dict[str, list[str]]:
    return {step.name: sorted(find_var_references(step.params)) for step in pipeline.steps}


def to_mermaid(pipeline: Pipeline, *, show_vars: bool = False) -> str:
    """A ``flowchart LR`` with one box per step (name and capability), an
    arrow per ``depends_on`` entry, and a comment line per execution layer.

    Node ids are positional (``s0``, ``s1``, ...) because step names may
    contain characters Mermaid ids cannot; the visible label carries the
    real name.
    """
    layers = execution_layers(pipeline)
    order = [name for layer in layers for name in layer]
    ids = {name: f"s{i}" for i, name in enumerate(order)}
    step_vars = _step_vars(pipeline) if show_vars else {}

    # Only <br/> inside labels: renderers with a strict security level
    # (GitHub's among them) strip other HTML tags.
    lines = ["flowchart LR", f"    %% {_mermaid_text(pipeline.name)}, generated by awe graph"]
    for index, layer in enumerate(layers):
        lines.append(f"    %% layer {index}: {', '.join(_mermaid_text(n) for n in layer)}")
        for name in layer:
            step = pipeline.step(name)
            label = f"{_mermaid_text(name)}<br/>({_mermaid_text(step.capability)})"
            if step_vars.get(name):
                label += f"<br/>vars: {_mermaid_text(', '.join(step_vars[name]))}"
            lines.append(f'    {ids[name]}["{label}"]')
    for name in order:
        for dep in pipeline.step(name).depends_on:
            lines.append(f"    {ids[dep]} --> {ids[name]}")
    return "\n".join(lines) + "\n"


def to_dot(pipeline: Pipeline, *, show_vars: bool = False) -> str:
    """A Graphviz ``digraph``: left to right, one rounded box per step, an
    edge per ``depends_on`` entry, and every execution layer pinned to one
    rank so steps that run side by side are drawn side by side."""
    layers = execution_layers(pipeline)
    step_vars = _step_vars(pipeline) if show_vars else {}
    lines = [
        f'digraph "{_dot_text(pipeline.name)}" {{',
        "    rankdir=LR;",
        '    node [shape=box, style=rounded, fontname="Helvetica"];',
    ]
    for index, layer in enumerate(layers):
        lines.append(f"    // layer {index}")
        for name in layer:
            step = pipeline.step(name)
            label = f"{name}\n{step.capability}"
            if step_vars.get(name):
                label += f"\nvars: {', '.join(step_vars[name])}"
            lines.append(f'    "{_dot_text(name)}" [label="{_dot_text(label)}"];')
        if len(layer) > 1:
            members = " ".join(f'"{_dot_text(n)}";' for n in layer)
            lines.append(f"    {{ rank=same; {members} }}")
    for layer in layers:
        for name in layer:
            for dep in pipeline.step(name).depends_on:
                lines.append(f'    "{_dot_text(dep)}" -> "{_dot_text(name)}";')
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_graph(pipeline: Pipeline, fmt: str = "mermaid", *, show_vars: bool = False) -> str:
    """Dispatch on ``fmt`` (one of :data:`FORMATS`)."""
    if fmt == "mermaid":
        return to_mermaid(pipeline, show_vars=show_vars)
    if fmt == "dot":
        return to_dot(pipeline, show_vars=show_vars)
    raise ValueError(f"unknown graph format {fmt!r}; expected one of {', '.join(FORMATS)}")


__all__ = ["FORMATS", "render_graph", "to_dot", "to_mermaid"]
